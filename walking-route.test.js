const assert=require('node:assert/strict');
const {distanceMeters,nextWeeklyCourse,parseWalkingResponse,fetchWalkingRoute,decodeRouteShape}=require('./walking-route');
const start=[30.833,121.514],end=[30.834,121.515];
const valid={code:'Ok',routes:[{distance:180,duration:150,geometry:{coordinates:[[start[1],start[0]],[end[1],end[0]]]}}]};
const course={day:5,start:'14:00',end:'15:35'};
assert.equal(nextWeeklyCourse([],new Date(2026,9,30,13)),null);
assert.equal(nextWeeklyCourse([course],new Date(2026,9,30,13)).offset,0);
assert.equal(nextWeeklyCourse([course],new Date(2026,9,30,14,30)).ongoing,true);
assert.equal(nextWeeklyCourse([course],new Date(2026,9,30,15,35)).offset,7);
assert.equal(nextWeeklyCourse([{...course,day:1}],new Date(2026,9,30,16)).offset,3);
assert.equal(distanceMeters(start,start),0);
assert.ok(distanceMeters(start,end)>100&&distanceMeters(start,end)<200);
assert.equal(parseWalkingResponse(valid,start,end).duration,150);
assert.throws(()=>parseWalkingResponse({code:'NoRoute'},start,end));
assert.throws(()=>parseWalkingResponse({...valid,routes:[{...valid.routes[0],duration:-1}]},start,end));
assert.throws(()=>parseWalkingResponse(valid,[31,122],end));
assert.throws(()=>decodeRouteShape('~'));
assert.deepEqual(decodeRouteShape('??'),[[0,0]]);
(async()=>{
  let requests=0;
  const route=await fetchWalkingRoute(start,end,{fetchImpl:async url=>{requests++;assert.ok(url.includes('routed-foot'));assert.ok(url.includes('121.514,30.833'));assert.ok(!url.includes('routed-car'));return{ok:true,json:async()=>valid}}});
  assert.equal(requests,1);assert.equal(route.distance,180);
  await assert.rejects(fetchWalkingRoute(start,[32,121],{fetchImpl:()=>{throw Error('不应请求')}}),/10 公里/);
  await assert.rejects(fetchWalkingRoute([NaN,1],end),/无效/);
  const controller=new AbortController();controller.abort();
  await assert.rejects(fetchWalkingRoute(start,end,{signal:controller.signal}),/取消/);
  let count=0;
  await assert.rejects(fetchWalkingRoute(start,end,{fetchImpl:async url=>{count++;if(count===1)throw Error('主服务失败');assert.ok(url.includes('valhalla'));assert.ok(decodeURIComponent(url).includes('pedestrian'));return{ok:true,json:async()=>({trip:{status:442}})}}}),/未找到/);
  assert.equal(count,2);
  console.log('Walking navigation: 20 checks passed');
})().catch(error=>{console.error(error);process.exitCode=1});
