const assert=require('node:assert/strict');
const {parseCourseText,courseConflicts}=require('./course-tools');
const sample='周五,14:00,15:35,数据结构,第二教学楼,A302,陈老师';
assert.equal(parseCourseText(sample).courses[0].day,5);
assert.equal(parseCourseText('\uFEFF星期,开始时间,结束时间,课程名,教学楼,教室,教师\r\n'+sample).courses.length,1);
assert.equal(parseCourseText(sample+'\n'+sample).courses.length,1);
assert.equal(parseCourseText('周五,15:35,14:00,数据结构,第二教学楼').issues.length,1);
assert.equal(parseCourseText('周五,25:00,26:00,数据结构,第二教学楼').issues.length,1);
assert.equal(parseCourseText('周八,14:00,15:35,数据结构,第二教学楼').issues.length,1);
assert.equal(parseCourseText('[]').issues.length,1);
assert.equal(parseCourseText('[bad').issues.length,1);
assert.equal(parseCourseText('[null]').issues.length,1);
assert.equal(parseCourseText('[{"day":5}]').issues.length,1);
const row=parseCourseText(sample).courses[0];
assert.equal(parseCourseText(JSON.stringify([row])).courses[0].name,'数据结构');
assert.equal(courseConflicts([row,{...row,start:'15:00',end:'16:00'}]).length,1);
assert.equal(courseConflicts([row,{...row,start:'15:35',end:'16:00'}]).length,0);
assert.equal(courseConflicts([row,{...row,day:6}]).length,0);
console.log('Course tools: 14 checks passed');
