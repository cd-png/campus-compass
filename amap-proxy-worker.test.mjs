import assert from 'node:assert/strict';
import worker from './amap-proxy-worker.mjs';
const env={AMAP_KEY:'test-key',AMAP_SECURITY_CODE:'test-secret'};
const request=(path,headers={Referer:'https://cd-png.github.io/campus-compass/'})=>new Request('https://proxy.example'+path,{headers});
assert.equal((await worker.fetch(request('/_AMapService/v3/place/text',{}),env)).status,403);
assert.equal((await worker.fetch(request('/_AMapService/v3/place/text',{Origin:'https://evil.example'}),env)).status,403);
assert.equal((await worker.fetch(request('/_AMapService/v3/ip'),env)).status,404);
assert.equal((await worker.fetch(request('/_AMapService/v3/place/text?key=other'),env)).status,403);
assert.equal((await worker.fetch(request('/_AMapService/v3/place/text'),{})).status,503);
let forwarded;
globalThis.fetch=async target=>{forwarded=new URL(target);return new Response('{"status":"1"}',{headers:{'Content-Type':'application/json'}})};
const result=await worker.fetch(request('/_AMapService/v3/place/text?key=test-key&jscode=evil&keywords=school'),env);
assert.equal(result.status,200);
assert.equal(forwarded.hostname,'restapi.amap.com');
assert.equal(forwarded.searchParams.get('jscode'),'test-secret');
assert.equal(result.headers.get('Access-Control-Allow-Origin'),'https://cd-png.github.io');
assert.equal((await result.text()).includes('test-secret'),false);
globalThis.fetch=async()=>new Response('test-secret');
assert.equal((await worker.fetch(request('/_AMapService/v3/place/text'),env)).status,502);
console.log('AMap proxy access control and secret forwarding checks passed');
